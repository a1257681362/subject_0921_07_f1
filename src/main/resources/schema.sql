-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- F1 合作社作业管理主链路。
-- 请求流水：所有新增/变更请求必须携带 request_no，全库唯一；
-- 重复提交命中流水即按幂等重放处理，唯一约束兜底并发。
CREATE TABLE IF NOT EXISTS t_request_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64) NOT NULL,
    biz_type VARCHAR(32) NOT NULL,
    biz_no VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_request_log_no UNIQUE (request_no)
);

-- 农机底账：不物理删除，停用走 status。
CREATE TABLE IF NOT EXISTS t_machine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_no VARCHAR(32) NOT NULL,
    machine_name VARCHAR(64) NOT NULL,
    machine_type VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_machine_no UNIQUE (machine_no)
);

-- 作业单：不物理删除；冲销另开 doc_type=REVERSAL 的反向单据（面积取负抵消原单）。
-- 面积以 track_area（轨迹核算）为准，reported_area（人工上报）仅作参考。
CREATE TABLE IF NOT EXISTS t_work_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    doc_type VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    ref_order_no VARCHAR(64),
    machine_no VARCHAR(32) NOT NULL,
    work_type VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    reported_area DECIMAL(12,2),
    track_area DECIMAL(12,2),
    reverse_reason VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_work_order_no UNIQUE (order_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-workorder-ledger', 'F1 农机底账与作业单主链路');
